def presentation_prompt(mode: str, detail_level: str) -> str:
    audience = (
        "面向临床工作人员，可展示策略版本、原因代码、候选集、原始候选分数和指南编号。"
        if mode == "clinician"
        else "面向患者，使用通俗中文；专业术语首次出现时用一句话解释。"
    )
    if detail_level == "detailed":
        depth = (
            "详细程度应与用户问题匹配，不要无条件套用病例报告。"
            "如果用户问医学概念，按‘直接定义—常见特点—需要警惕的变化—来源’回答；"
            "如果用户问当前病例为何转诊或要求归因，再按‘直接结论—视觉证据—症状复核—指南依据—不确定性—下一步’组织。"
        )
    else:
        depth = "生成简明回答，通常为200至400个中文字，优先回答当前问题和下一步行动。"
    return f"{audience}{depth}"

